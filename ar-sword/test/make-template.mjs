import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { findCandidates, templateSamples } from '../site/detect.js';

const root = new URL('..', import.meta.url).pathname;
const W = 540, H = 720;
const gray = execFileSync('ffmpeg', ['-nostdin', '-v', 'error', '-i', `${root}test/photos/0442.jpg`, '-vf', `scale=${W}:${H}`, '-f', 'rawvideo', '-pix_fmt', 'gray', '-'], { maxBuffer: 1 << 26 });
const [hit] = findCandidates(new Uint8Array(gray), W, H);
if (!hit) throw new Error('reference photo not detected');
const samples = templateSamples(new Uint8Array(gray), W, H, hit.quad);
writeFileSync(`${root}site/template.js`, `// Generated by test/make-template.mjs from test/photos/0442.jpg.\nexport const TEMPLATE = '${Buffer.from(samples).toString('base64')}';\n`);
console.log('template written, quad', hit.quad.map((p) => p.map(Math.round)));
